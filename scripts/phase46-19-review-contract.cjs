#!/usr/bin/env node
'use strict';
/** Model-level/offline source contract, never browser or production certification. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
require('./phase46-2-source-loader.cjs');
const {emptyInvestigationCase,addCaseNote,addCaseReference,projectInvestigationCase}=require('../apps/aim-next/src/features/investigation/evidenceCase.ts');
const {prepareInvestigationReview}=require('../apps/aim-next/src/features/investigation/evidenceReviewPreparation.ts');
let passed=0;
function check(label,action){try{action();passed++;}catch(e){throw new Error(label+': '+e.message);}}
const e=(key,ownerRecordId='C1')=>({key,domain:'COR',kind:'Calculation trace',ownerRecordId,
  sourceRecordId:key,reference:`REF-${key}`,supportingReference:null,revision:'r1',
  reportedAt:'2026-10-01T10:00:00Z',status:'DRAFT',authority:'SOURCE_REFERENCE'});
const entries=[e('K1'),e('K2')];
const sources=[{domain:'COR',state:'ready',indexed:2,totalReported:3,truncated:true},
  {domain:'INS',state:'rejected',indexed:99,totalReported:99,truncated:true}];
let state=addCaseReference(emptyInvestigationCase('A1'),'A1','K1',entries);
state=addCaseNote(state,'A1','OBSERVATION','Reported observation','K1',entries);
state=addCaseNote(state,'A1','QUESTION','Unresolved question','K1',entries);
state=addCaseNote(state,'A1','NEXT_STEP','Potential follow-up',null,entries);
const project=(asset,index=entries)=>projectInvestigationCase(state,asset,index);
const review=prepareInvestigationReview(project('A1'),sources);
check('asset identity retained',()=>assert.equal(review.assetId,'A1'));
check('only bookmarked current evidence shown',()=>assert.deepEqual(review.references.map(x=>x.key),['K1']));
check('observations grouped as drafts',()=>assert.deepEqual(review.observations.map(x=>x.text),['Reported observation']));
check('questions grouped as drafts',()=>assert.deepEqual(review.questions.map(x=>x.text),['Unresolved question']));
check('next steps grouped as proposed',()=>assert.deepEqual(review.nextSteps.map(x=>x.text),['Potential follow-up']));
check('linked note retains current evidence pointer',()=>assert.equal(review.questions[0].evidence.key,'K1'));
check('unlinked count shows deliberately unanchored entry',()=>assert.equal(review.unlinkedNoteCount,1));
check('no approval field inferred',()=>assert.ok(!('approved' in review)));
check('no review status inferred',()=>assert.ok(!('reviewStatus' in review)));
check('no persistence key inferred',()=>assert.ok(!('storageKey' in review)));
check('no document URL inferred',()=>assert.ok(!('url' in review)));
check('rejected source remains rejected',()=>assert.equal(review.sources[1].state,'rejected'));
check('rejected source index count suppressed',()=>assert.equal(review.sources[1].indexed,0));
check('rejected source reported count suppressed',()=>assert.equal(review.sources[1].totalReported,0));
check('rejected source truncated flag suppressed',()=>assert.equal(review.sources[1].truncated,false));
check('ready source limitation preserved',()=>assert.equal(review.sources[0].truncated,true));
check('missing source flagged',()=>assert.match(review.limitations.join(' '),/disconnected or rejected/));
check('partial index flagged',()=>assert.match(review.limitations.join(' '),/index reached its display limit/));
check('notes explicitly not findings',()=>assert.match(review.limitations.join(' '),/not an engineering assessment/));
check('note links do not substantiate draft',()=>assert.match(review.limitations.join(' '),/not verification/));
const withdrawn=prepareInvestigationReview(project('A1',[]),sources);
check('withdrawn source suppressed',()=>assert.deepEqual(withdrawn.references,[]));
check('anchored observation suppressed',()=>assert.deepEqual(withdrawn.observations,[]));
check('anchored question suppressed',()=>assert.deepEqual(withdrawn.questions,[]));
check('unlinked note remains explicit',()=>assert.equal(withdrawn.nextSteps.length,1));
check('withdrawn count surfaced',()=>assert.equal(withdrawn.withdrawnReferenceCount,1));
check('withdrawal limitation surfaced',()=>assert.match(withdrawn.limitations.join(' '),/unavailable in the current index/));
const rotated=prepareInvestigationReview(project('A2'),sources);
check('asset rotation suppresses references',()=>assert.equal(rotated.references.length,0));
check('asset rotation suppresses notes',()=>assert.equal(rotated.nextSteps.length,0));
check('asset rotation uses new asset',()=>assert.equal(rotated.assetId,'A2'));
const standalone=prepareInvestigationReview(project('A1'));
check('standalone metadata not invented',()=>assert.equal(standalone.sources.length,0));
check('standalone limitation explicit',()=>assert.match(standalone.limitations.join(' '),/not supplied to this preview/));
const forged=project('A1');
const tampered=prepareInvestigationReview({...forged,notes:forged.notes.map(n=>({...n,evidence:n.evidence?e('K1','PRIVATE'):null}))});
check('cross-owner forged source pointer suppressed',()=>assert.equal(tampered.questions.length,0));
check('unanchored draft survives malformed foreign pointer',()=>assert.equal(tampered.nextSteps.length,1));
const root=path.resolve(__dirname,'..');const read=(f)=>fs.readFileSync(path.join(root,f),'utf8');
const model=read('apps/aim-next/src/features/investigation/evidenceReviewPreparation.ts');
const ui=read('apps/aim-next/src/features/investigation/EngineeringInvestigationCase.tsx');
const nav=read('apps/aim-next/src/features/investigation/EngineeringEvidenceNavigator.tsx');
const css=read('apps/aim-next/src/styles.css');
check('model accepts current projected case only',()=>assert.match(model,/projected:ProjectedCase/));
check('model never fetches or uses storage',()=>assert.doesNotMatch(model,/\bfetch\s*\(|localStorage|sessionStorage|indexedDB|XMLHttpRequest/));
check('UI never fetches or uses storage',()=>assert.doesNotMatch(ui,/\bfetch\s*\(|localStorage|sessionStorage|indexedDB|XMLHttpRequest/));
check('no clipboard/export features in UI',()=>assert.doesNotMatch(ui,/createObjectURL|clipboard\.|download=|exportFile/));
check('UI uses current case projection',()=>assert.match(ui,/prepareInvestigationReview\(working,sourceCoverage\)/));
check('UI retains existing scope-safe working case',()=>assert.match(ui,/projectInvestigationCase\(draft,assetId,entries\)/));
check('navigator supplies independent source states',()=>assert.match(nav,/sourceCoverage=\{\[/));
check('navigator does not bypass authorization',()=>assert.match(nav,/context\.corrosion\.state==="ready"\?corrosion\.entries\.length:0/));
check('read-only preview disclosure',()=>assert.match(ui,/aria-label="Read-only investigation review preparation"/));
check('preview denies approval and submission',()=>assert.match(ui,/No submission, export, download, copying, persistence, sign-off, or approval/));
check('preview displays source record identity',()=>assert.match(ui,/source \{item\.sourceRecordId\}/));
check('preview has keyboard focus styling',()=>assert.match(css,/\.engineering-investigation-review :is\(summary,button\):focus-visible/));
check('preview has mobile layout',()=>assert.match(css,/@media\(max-width:480px\)\{\.engineering-investigation-review-body/));
check('preview has forced-colors support',()=>assert.match(css,/@media\(forced-colors:active\)\{\.engineering-investigation-review/));
console.log(`PASS Phase 46.19 offline review-preparation contract: ${passed}/${passed}. NOT TypeScript 7/Vitest/Vite/Chromium.`);
