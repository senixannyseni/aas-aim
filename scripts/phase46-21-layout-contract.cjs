#!/usr/bin/env node
'use strict';
/** Scoped UI-layout contract. Does NOT mount React or authorize engineering actions. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
require('./phase46-2-source-loader.cjs');
const root=path.resolve(__dirname,'..');
const source=(name)=>fs.readFileSync(path.join(root,name),'utf8');
const model=source('apps/aim-next/src/features/investigation/investigationFocusModel.ts');
const navigation=source('apps/aim-next/src/features/investigation/EngineeringEvidenceNavigator.tsx');
const caseUi=source('apps/aim-next/src/features/investigation/EngineeringInvestigationCase.tsx');
const style=source('apps/aim-next/src/styles.css');
const release=source('scripts/release-evidence.mjs');
const runner=source('scripts/release-validation.sh');
const {visibleInvestigationPanels,focusForSourceInspection,INVESTIGATION_FOCUS_OPTIONS}=require('../apps/aim-next/src/features/investigation/investigationFocusModel.ts');
let passed=0;
const t=(label,fn)=>{try{fn();passed++;}catch(error){throw new Error(`${label}: ${error.message}`);}};
t('four distinct presentation modes',()=>assert.deepEqual(INVESTIGATION_FOCUS_OPTIONS.map(item=>item.id),['EVIDENCE','OBSERVATIONS','CASE','ALL']));
t('default shows all three panels',()=>assert.deepEqual(visibleInvestigationPanels('ALL'),{evidence:true,observations:true,caseWork:true}));
t('evidence shows only the explorer',()=>assert.deepEqual(visibleInvestigationPanels('EVIDENCE'),{evidence:true,observations:false,caseWork:false}));
t('observations shows only source patterns',()=>assert.deepEqual(visibleInvestigationPanels('OBSERVATIONS'),{evidence:false,observations:true,caseWork:false}));
t('case shows only working case',()=>assert.deepEqual(visibleInvestigationPanels('CASE'),{evidence:false,observations:false,caseWork:true}));
t('source inspect from case reveals evidence',()=>assert.equal(focusForSourceInspection('CASE'),'EVIDENCE'));
t('source inspect from observations reveals evidence',()=>assert.equal(focusForSourceInspection('OBSERVATIONS'),'EVIDENCE'));
t('source inspect from all preserves all',()=>assert.equal(focusForSourceInspection('ALL'),'ALL'));
t('focus model is frozen',()=>assert(Object.isFrozen(INVESTIGATION_FOCUS_OPTIONS)&&Object.isFrozen(visibleInvestigationPanels('CASE'))));
t('no transport calls in focus model',()=>assert.doesNotMatch(model, /\bfetch\s*\(|localStorage|sessionStorage|indexedDB|XMLHttpRequest/));
t('compatibility default is all',()=>assert.match(navigation,/useState<InvestigationFocus>\("ALL"\)/));
t('navigation focus controlled buttons',()=>assert.match(navigation,/aria-pressed=\{focusMode===id\}/));
t('navigation uses published projection',()=>assert.match(navigation,/visibleInvestigationPanels\(focusMode\)/));
t('case panel hidden not removed',()=>assert.match(navigation,/hidden=\{!focusPanels\.caseWork\}/));
t('evidence panel hidden not removed',()=>assert.match(navigation,/hidden=\{!focusPanels\.evidence\}/));
t('observation panel hidden not removed',()=>assert.match(navigation,/hidden=\{!focusPanels\.observations\}/));
t('only one EngineeringInvestigationCase mount point',()=>assert.equal((navigation.match(/<EngineeringInvestigationCase\b/g)||[]).length,1));
t('selected asset id still passed',()=>assert.match(navigation,/assetId=\{context\.asset\.id\}/));
t('authorizations still independently guarded',()=>assert.match(navigation,/context\.corrosion\.state==="ready"/));
t('trace selection reveals source',()=>assert.match(navigation,/setFocusMode\(focusForSourceInspection\)/));
t('case focus opens native disclosure',()=>assert.match(caseUi,/focusRequested&&caseDisclosure\.current/));
t('case scope not persisted',()=>assert.doesNotMatch(caseUi,/\bfetch\s*\(|localStorage|sessionStorage|indexedDB|XMLHttpRequest/));
t('case source boundary still projects',()=>assert.match(caseUi,/projectInvestigationCase\(draft,assetId,entries\)/));
t('desktop four-column modes',()=>assert.match(style,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/));
t('mobile two-column modes',()=>assert.match(style,/@media\(max-width:850px\).*?grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/));
t('explicit hidden styles',()=>assert.match(style,/\.engineering-workspace-panel\[hidden\]\{display:none!important\}/));
t('keyboard focus visible',()=>assert.match(style,/\.engineering-workspace-focus button:focus-visible/));
t('forced colors supported',()=>assert.match(style,/@media\(forced-colors:active\).*?\.engineering-workspace-focus button/));
t('reduced motion supported',()=>assert.match(style,/@media\(prefers-reduced-motion:reduce\).*?\.engineering-workspace-focus button/));
t('phase release gate declared',()=>assert.match(release,/phase46_21_investigation_focus/));
t('phase release gate is executed',()=>assert.match(runner,/phase46_21_investigation_focus node scripts\/phase46-21-layout-contract\.cjs/));
console.log(`PASS Phase 46.21 focus contract: ${passed}/${passed}. NOT React/Vite/mounted Chromium acceptance.`);
