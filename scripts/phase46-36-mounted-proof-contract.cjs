#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const bash=read('scripts/release-validation.sh');
const registry=read('scripts/release-evidence.mjs');
const capture=read('apps/aim-next/scripts/browser-phase46-36-visual-proof.py');
const unit=read('apps/aim-next/scripts/test_browser_phase46_36_visual_proof.py');
const workflow=read('.github/workflows/aim-next-ui.yml');
let count=0;
const check=(value,message)=>{assert(value,message);count++};
check(bash.includes('run_gate phase46_36_mounted_proof_contract node scripts/phase46-36-mounted-proof-contract.cjs'),'release runs Phase 46.36 contract');
check(registry.includes("'phase46_36_mounted_proof_contract'"),'evidence lists phase contract');
check(registry.indexOf("'phase46_35_visual_composition'")<registry.indexOf("'phase46_36_mounted_proof_contract'"),'version-ordered contract');
check(bash.includes('run_gate mounted_chromium_visual_proof python3 apps/aim-next/scripts/browser-phase46-36-visual-proof.py "${browser_args[@]}"'),'real mounted capture registered');
check(registry.includes("'mounted_chromium_visual_proof'"),'capture evidence gate registered');
check(bash.indexOf('run_gate vite_preview_ready')<bash.indexOf('run_gate mounted_chromium_visual_proof'),'capture only after running preview');
check(bash.indexOf('run_gate mounted_chromium_navigation_journey')<bash.indexOf('run_gate mounted_chromium_visual_proof'),'capture after existing browser journey');
check(bash.indexOf('run_gate mounted_chromium_visual_proof')<bash.indexOf('run_gate phase46_10_release_integrity'),'capture before integrity gate');
check(workflow.includes('qa/runtime/phase46-36-mounted-visuals/'),'CI uploads the screenshots on failure/success');
check(read('.github/workflows/aim-next-lockfile-candidate.yml').includes('qa/runtime/phase46-36-mounted-visuals/'),'lockfile-candidate CI preserves visual proof');
for(const f of ['--bandha-v18-deep','--bandha-v18-paper','--bandha-v18-copper','--bandha-v18-mint'])check(capture.includes(f),'bandha computed token '+f);
for(const phrase of ['getComputedStyle','page.screenshot','pageerror','clientWidth','scrollWidth','MOUNTED_REACT_APP','syntheticScreenshot\': False','DISCONNECTED_NO_FIXTURE','engineeringApproval\': False','id="root"'])check(capture.includes(phrase),'non-synthetic QA contract '+phrase);
check(capture.includes('page.goto(base + \'/\' + route'),'capture targets built preview server');
check(capture.includes('Asset Register'),'capture screenshot covers Asset Register route');
check(!capture.includes('page.set_content'),'no standalone synthetic HTML masquerading as mounted app');
check(unit.includes('test_rejects_color_drifts'),'unit tests reject incorrect palette');
check(unit.includes('test_detects_real_horizontal_overflow'),'unit tests reject overflow');
check(read('apps/aim-next/src/main.tsx').includes('createRoot(rootElement).render('),'source still mounts real React');
check(read('apps/aim-next/src/styles.css').includes('--bandha-v18-deep:#101b1d;'),'Phase46.34 palette source retained');
check(read('apps/aim-next/src/styles.css').includes("font-family:'DM Sans'"),'AIM font remains untouched');
console.log(`PASS Phase 46.36 mounted visual proof contract ${count}/${count}`);
