#!/usr/bin/env node
'use strict';
/** Executable isolated model and source-contract checks; NOT mounted React. */
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
require('./phase46-2-source-loader.cjs');
const {emptyInvestigationCase,addCaseReference,addCaseNote,updateCaseNote,projectInvestigationCase,CASE_NOTE_LENGTH}=require('../apps/aim-next/src/features/investigation/evidenceCase.ts');
const {prepareInvestigationReview}=require('../apps/aim-next/src/features/investigation/evidenceReviewPreparation.ts');
const {summarizeCaseDesk}=require('../apps/aim-next/src/features/investigation/investigationCaseDesk.ts');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const caseCode=read('apps/aim-next/src/features/investigation/EngineeringInvestigationCase.tsx');
const modelCode=read('apps/aim-next/src/features/investigation/evidenceCase.ts');
const nav=read('apps/aim-next/src/features/investigation/EngineeringEvidenceNavigator.tsx');
const css=read('apps/aim-next/src/styles.css');
const release=read('scripts/release-evidence.mjs');
const runner=read('scripts/release-validation.sh');
const e=(key,domain)=>({key,domain,kind:'Calculation trace',ownerRecordId:key+'-owner',sourceRecordId:key+'-source',reference:key,status:'REPORTED',revision:null,reportedAt:null,supportingReference:null,authority:'SOURCE_REFERENCE'});
const cor=e('COR-A','COR'),ins=e('INS-B','INS');const all=[cor,ins];
let state=emptyInvestigationCase('A1');state=addCaseReference(state,'A1','COR-A',all);state=addCaseReference(state,'A1','INS-B',all);
state=addCaseNote(state,'A1','QUESTION','Check reported corrosion rate','COR-A',all);
state=addCaseNote(state,'A1','OBSERVATION','Check inspection record',null,all);
let passed=0;function check(name,fn){try{fn();passed++}catch(error){throw Error(`${name}: ${error.message}`)}}
const edit=updateCaseNote(state,'A1',1,'NEXT_STEP','Propose inspection review','INS-B',all);
check('existing note updated',()=>assert.equal(edit.notes[0].text,'Propose inspection review'));
check('type updated',()=>assert.equal(edit.notes[0].kind,'NEXT_STEP'));
check('relink only indexed pointer',()=>assert.equal(edit.notes[0].evidenceKey,'INS-B'));
check('preserve original note id',()=>assert.equal(edit.notes[0].id,state.notes[0].id));
check('preserve next id',()=>assert.equal(edit.nextId,state.nextId));
check('preserve note count',()=>assert.equal(edit.notes.length,state.notes.length));
check('preserve reference selection',()=>assert.deepEqual(edit.referenceKeys,state.referenceKeys));
check('do not mutate input',()=>assert.equal(state.notes[0].text,'Check reported corrosion rate'));
check('unrelated note unchanged',()=>assert.equal(edit.notes[1],state.notes[1]));
check('asset mismatch rejects',()=>assert.equal(updateCaseNote(state,'A2',1,'QUESTION','New',null,all),state));
check('missing note rejects',()=>assert.equal(updateCaseNote(state,'A1',999,'QUESTION','New',null,all),state));
check('invalid note ID rejects',()=>assert.equal(updateCaseNote(state,'A1',1.1,'QUESTION','New',null,all),state));
check('invalid type rejects',()=>assert.equal(updateCaseNote(state,'A1',1,'APPROVED','New',null,all),state));
check('blank rejects',()=>assert.equal(updateCaseNote(state,'A1',1,'QUESTION','  ',null,all),state));
check('length cap rejects',()=>assert.equal(updateCaseNote(state,'A1',1,'QUESTION','x'.repeat(CASE_NOTE_LENGTH+1),null,all),state));
check('unknown source rejected',()=>assert.equal(updateCaseNote(state,'A1',1,'QUESTION','New','UNKNOWN',all),state));
check('not selected source rejected',()=>assert.equal(updateCaseNote(state,'A1',1,'QUESTION','New','COR-C',[...all,e('COR-C','COR')]),state));
check('withdrawn target rejected',()=>assert.equal(updateCaseNote(state,'A1',1,'QUESTION','New','INS-B',[cor]),state));
check('withdrawn original cannot be detached',()=>assert.equal(updateCaseNote(state,'A1',1,'QUESTION','New',null,[ins]),state));
check('safe projected note hidden after withdrawal',()=>assert.equal(projectInvestigationCase(edit,'A1',[cor]).notes.some(x=>x.note.id===1),false));
check('unlinked note still projected',()=>assert.equal(projectInvestigationCase(edit,'A1',[cor]).notes.length,1));
check('same edit returns original',()=>assert.equal(updateCaseNote(state,'A1',1,'QUESTION','Check reported corrosion rate','COR-A',all),state));
const review=prepareInvestigationReview(projectInvestigationCase(edit,'A1',all));
const overview=summarizeCaseDesk(review);
check('review updates next steps',()=>assert.equal(overview.nextStepCount,1));
check('review updates observations',()=>assert.equal(overview.observationCount,1));
check('review updates question count',()=>assert.equal(overview.questionCount,0));
check('review count unchanged',()=>assert.equal(overview.noteCount,2));
check('case render only authorized notes',()=>assert(caseCode.includes('working.notes.find(({note})=>note.id===id)')));
check('case updates by original ID',()=>assert(caseCode.includes('updateCaseNote(draft,assetId,editingNoteId,noteType,noteText,evidenceKey,entries)')));
check('cancel edit does not call setter on state',()=>assert(caseCode.includes("const cancelEditing=()=>{setEditingNoteId(null);setNoteText('');")));
check('save and cancel explicit',()=>assert(caseCode.includes('Save draft changes')&&caseCode.includes('Cancel edit')));
check('note editor prefilled with exact existing text',()=>assert(caseCode.includes('setNoteText(found.note.text)')));
check('source pointer restored from existing note',()=>assert(caseCode.includes("setAttachedKey(found.note.evidenceKey??'')")));
check('no automatic note created by handoff',()=>assert(caseCode.includes('stageEvidenceHandoff(draft,assetId,entries,handoffRequest)')));
check('case remains temporary',()=>assert(caseCode.includes('Session-only working notes')));
check('no model transport or local persistence',()=>assert.doesNotMatch(modelCode+caseCode,/localStorage|sessionStorage|indexedDB|fetch\(/));
check('source authorization unchanged',()=>assert(nav.includes('context.corrosion.state==="ready"?corrosion.entries:[]')));
check('edit banner styled',()=>assert(css.includes('.engineering-case-edit-banner{')));
check('mobile edit actions styled',()=>assert(css.includes('@media(max-width:620px){.engineering-case-note-actions')));
check('forced-colors fallback retained',()=>assert(css.includes('@media(forced-colors:active){.engineering-case-edit-banner')));
check('gate registered',()=>assert(release.includes("'phase46_31_draft_revision'")));
check('gate execution wired',()=>assert(runner.includes('run_gate phase46_31_draft_revision node scripts/phase46-31-draft-revision-contract.cjs')));
console.log(`PASS Phase 46.31 draft revision model + source contracts: ${passed}/${passed}. NOT React/Vite runtime.`);
