// Runtime traces are intentionally untracked. A committed historical JSON trace
// must never be mistaken for evidence generated by the current CI execution.
const reportPath = join(root, 'qa', 'runtime', 'phase32-release-gates.json');
export function digestLockfile(file) {
  return existsSync(file) ? createHash('sha256').update(readFileSync(file)).digest('hex') : null;
}
/** Release evidence must describe the same frozen lockfile at start and completion. */
export function verifyLockfileContinuity(recordedDigest, currentDigest) {
  if (typeof recordedDigest !== 'string' || !/^[a-f0-9]{64}$/.test(recordedDigest)) {
    throw new Error('Missing or invalid starting lockfile digest');
  }
  if (typeof currentDigest !== 'string' || !/^[a-f0-9]{64}$/.test(currentDigest)) {
    throw new Error('Frozen lockfile is missing at release completion');
  }
  if (recordedDigest !== currentDigest) {
    throw new Error('Frozen lockfile changed after the release trace started; restart all gates');
  }
  return currentDigest;
}
function gitCommit() {
  const result = spawnSync('git', ['rev-parse', '--verify', 'HEAD'], {cwd:root, encoding:'utf8',timeout:2000});
  return result.status === 0 && /^[a-f0-9]{40}$/.test(result.stdout.trim()) ? result.stdout.trim() : null;
}
export function initialEvidence({nodeVersion, lockfileSha256=null, commitSha=null, runId=null, startedAt}) {
  return {
    phase:32,
    status:'IN_PROGRESS',
    releaseApproved:false,
    humanLockfileReview:'NOT_VERIFIED',
    mountedAppBrowserAudit:'NOT_EXECUTED',
    source:{commitSha, lockfileSha256, ciRunId:runId},
    environment:{nodeVersion},
    startedAt,
    currentGate:null,
    passedGates:[],
    failedGate:null,
    failureExitCode:null,
    expectedGates:[...GATES],
    warning:'A passing script is not an approval for production or any engineering calculation.'
  };
}
export function transition(evidence, event, gate=null, exitCode=null) {
  if (event === 'enter') {
    if (evidence.status !== 'IN_PROGRESS' || evidence.currentGate !== null) throw new Error('Cannot enter gate when another gate is open or run is finished');
    if (gate !== GATES[evidence.passedGates.length]) throw new Error(`Expected next gate ${GATES[evidence.passedGates.length]}, not ${gate}`);
    return {...evidence, currentGate:gate};
  }
  if (event === 'pass') {
    if (evidence.status !== 'IN_PROGRESS' || evidence.currentGate !== gate || !GATES.includes(gate)) throw new Error('Cannot pass a gate that is not running');
    const passedGates=[...evidence.passedGates,gate];
    return {...evidence, currentGate:null, passedGates, mountedAppBrowserAudit:gate==='mounted_chromium_78x4_audit' ? 'PASSED' : evidence.mountedAppBrowserAudit};
  }
  if (event === 'fail') {
    if (evidence.status !== 'IN_PROGRESS') throw new Error('Cannot fail a finished run');
    if (!Number.isInteger(exitCode) || exitCode <= 0 || exitCode > 255) throw new Error('Failure must supply nonzero exit code');
    if (gate && gate !== evidence.currentGate) throw new Error('Failed gate differs from running gate');
    return {...evidence,status:'FAILED', currentGate:null,failedGate:evidence.currentGate || 'UNKNOWN',failureExitCode:exitCode};
  }
  if (event === 'complete') {
    if (evidence.status !== 'IN_PROGRESS' || evidence.currentGate !== null || evidence.passedGates.length !== GATES.length) throw new Error('Cannot mark incomplete run as passed');
    if (evidence.passedGates.some((name,i) => name !== GATES[i])) throw new Error('Gate order or identity mismatch');
    if (!evidence.source.lockfileSha256) throw new Error('A genuine lockfile is required for runtime validation');
    return {...evidence,status:'RUNTIME_GATES_PASSED_AWAITING_REVIEW',completedAt:new Date().toISOString()};
  }
  throw new Error(`Unsupported evidence transition: ${event}`);
}
export function writeReport(report, destination = reportPath) {
  mkdirSync(dirname(destination),{recursive:true});
  const temporary=destination+'.tmp';
  try {
    writeFileSync(temporary,JSON.stringify(report,null,2)+'\n');
    renameSync(temporary,destination);
  } finally {
    // A failed rename must not leave a partial candidate trace in the workspace.
    rmSync(temporary,{force:true});
  }
}
/** Remove any stale outcome BEFORE attempting to initialize a fresh run. */
export function beginEvidenceRun(destination, report, persist = writeReport) {
  rmSync(destination,{force:true});
  persist(report,destination);
}
function cli() {
  const [command, gate, rawExit] = process.argv.slice(2);
  if (command==='start') {
    const report=initialEvidence({nodeVersion:process.version,lockfileSha256:digestLockfile(join(root,'pnpm-lock.yaml')),commitSha:gitCommit(),runId:process.env.GITHUB_RUN_ID||null,startedAt:new Date().toISOString()});
    beginEvidenceRun(reportPath,report);
    console.log(`Phase 32 gate trace initialized: ${reportPath}`);
    return;
  }
  const evidence=JSON.parse(readFileSync(reportPath,'utf8'));
  if (command === 'complete') {
    // The final gate independently checks this too, but direct evidence CLI
    // invocations must not bypass lockfile continuity.
    verifyLockfileContinuity(evidence.source.lockfileSha256, digestLockfile(join(root,'pnpm-lock.yaml')));
  }
  const next=transition(evidence,command,gate||null,rawExit===undefined?null:Number(rawExit));
  writeReport(next);
  console.log(`${command.toUpperCase()}: ${gate||next.status}`);
}
if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) cli();
