import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { makeCandidateReport, formatReviewMarkdown } from "./lockfile-candidate-report.mjs";

const pin = (name, versions = {react:"19.3.1"}) => ({name, packageManager:"pnpm@12.14.0", dependencies:versions, devDependencies:{}});
const fake = Buffer.from("lockfileVersion: '9.0'\nimporters:\n  .: {}\n");
const args = {lockfile:fake, aimManifest:pin("@bandha/aim-next"),webManifest:pin("@bandha/aim-web"),nodeVersion:"v24.0.0",pnpmVersion:"12.14.0"};

describe("Phase 25 lockfile review inventory, not lockfile resolution",()=>{
  it("records a reproducible SHA256 without claiming production verification",()=>{
    const review=makeCandidateReport({...args,gateStatus:"PASS"});
    assert.equal(review.lockfile.sha256, createHash("sha256").update(fake).digest("hex"));
    assert.equal(review.productionValidated,false);
    assert.equal(review.status,"CANDIDATE_AWAITING_HUMAN_REVIEW");
    assert.match(formatReviewMarkdown(review),/Mounted 78-screen browser tests: \*\*INCLUDED IN PASSING CANDIDATE GATE\*\*/);
  });
  it("fails closed without a genuine nonempty pnpm lockfile",()=>{
    assert.throws(()=>makeCandidateReport({...args,lockfile:Buffer.from("")}),/nonempty/);
    assert.throws(()=>makeCandidateReport({...args,lockfile:Buffer.from("faked")}),/lockfileVersion/);
  });
  it("accepts valid top-level pnpm versions after comments and across YAML documents",()=>{
    const withHeader = Buffer.from("# generated by pnpm\n\nlockfileVersion: '9.0'\nimporters:\n  .: {}\n");
    assert.equal(makeCandidateReport({...args,lockfile:withHeader}).lockfile.bytes,withHeader.length);
    const multipleDocs = Buffer.from("lockfileVersion: '9.0'\nconfigDependencies: {}\n---\nlockfileVersion: '9.0'\nimporters: {}\n");
    assert.equal(makeCandidateReport({...args,lockfile:multipleDocs}).lockfile.bytes,multipleDocs.length);
  });
  it("rejects fake, nested, commented-out, or inconsistent pnpm versions",()=>{
    for (const content of [
      "# lockfileVersion: '9.0'\n",
      "settings:\n  lockfileVersion: '9.0'\n",
      "lockfileVersion: '9.0'\n---\nlockfileVersion: '10.0'\n"
    ]) {
      assert.throws(()=>makeCandidateReport({...args,lockfile:Buffer.from(content)}),/top-level pnpm lockfileVersion/);
    }
  });
  it("rejects inconsistent or non-exact manifest pins",()=>{
    assert.throws(()=>makeCandidateReport({...args,webManifest:pin("@bandha/aim-web",{react:"^19.3.1"})}),/Non-exact/);
    assert.throws(()=>makeCandidateReport({...args,webManifest:pin("@bandha/aim-web",{react:"19.2.0"})}),/Conflicting/);
    assert.throws(()=>makeCandidateReport({...args,webManifest:{...args.webManifest,packageManager:"pnpm@11.0.0"}}),/Unexpected package manager/);
  });
  it("accepts only enumerated gate statuses",()=>{
    assert.throws(()=>makeCandidateReport({...args,gateStatus:"RELEASE_APPROVED"}),/Invalid candidate/);
    assert.equal(makeCandidateReport(args).candidateRuntimeGates,"NOT_EXECUTED");
  });
});

describe('Phase 46.3 local workspace dependency policy',()=>{
  it('accepts the shared platform workspace link in both manifests',()=>{
    const aim=pin('@bandha/aim-next',{react:'19.3.1','@bandha/aim-platform':'workspace:*'});
    const web=pin('@bandha/aim-web',{react:'19.3.1','@bandha/aim-platform':'workspace:*'});
    const review=makeCandidateReport({...args,aimManifest:aim,webManifest:web});
    assert.equal(review.directDependencyPins.length,2);
    assert.equal(review.directDependencyPins[0].dependencies['@bandha/aim-platform'],'workspace:*');
  });
  it('rejects workspace links on unapproved packages and loose registry versions',()=>{
    const bad=pin('@bandha/aim-next',{react:'19.3.1',lodash:'workspace:*'});
    assert.throws(()=>makeCandidateReport({...args,aimManifest:bad}),/Non-exact/);
    const mismatched=pin('@bandha/aim-next',{react:'19.3.1','@bandha/aim-platform':'workspace:^'});
    assert.throws(()=>makeCandidateReport({...args,aimManifest:mismatched}),/Non-exact/);
  });
});
